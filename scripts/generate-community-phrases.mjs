import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const communityResearchUrl=new URL('../data/chinese-rental-research.json',import.meta.url);
const communityModuleUrl=new URL('../web/community-phrases.mjs',import.meta.url);
const communityResearch=JSON.parse(await readFile(communityResearchUrl,'utf8'));
if(!Array.isArray(communityResearch.entries)||communityResearch.entries.length!==communityResearch.entryCount)throw Error('Research phrase count is inconsistent');
const communitySeen=new Set();
for(const entry of communityResearch.entries){
  if(!entry.ru?.trim()||!entry.zh?.trim()||communitySeen.has(entry.ru))throw Error('Invalid or duplicate research phrase: '+entry.ru);
  communitySeen.add(entry.ru);
}
const communityRows=communityResearch.entries.map(({ru,zh,category})=>[ru,zh,category]);
const communityMetadata={
  version:communityResearch.version,checkedAt:communityResearch.checkedAt,entryCount:communityRows.length,
  sourceFile:'data/chinese-rental-research.json',scope:communityResearch.scope,
  factPolicy:'Vocabulary only; a phrase never confirms an apartment feature or permission.',
  review:'curated-language-not-a-property-fact',
  sources:communityResearch.sources.map(({id,url,title,status})=>({id,url,title,status})),
  entries:communityResearch.entries.map(({id,sourceIds})=>({id,sourceIds})),
};
const communityOutput='// Generated by scripts/generate-community-phrases.mjs from the attributed research corpus.\n'+
  'export const COMMUNITY_RENTAL_ENTRIES='+JSON.stringify(communityRows)+';\n'+
  'export const COMMUNITY_RENTAL_RULES=Object.fromEntries(COMMUNITY_RENTAL_ENTRIES.map(([ru,zh])=>[ru,zh]));\n'+
  'export const COMMUNITY_RENTAL_META='+JSON.stringify(communityMetadata)+';\n';
await writeFile(communityModuleUrl,communityOutput);
process.stdout.write('Generated '+communityRows.length+' community rental phrases: '+fileURLToPath(communityModuleUrl)+'\n');
