def prepare():
    rows=[]
    for index,(ru,zh,title,body) in enumerate(SITUATIONS,1):
        group=f'authored-bilingual-property-v2-{index}'
        common={'groupId':group,'status':'project-authored','source':'project-authored:balanced-bilingual-seed-v2',
            'fictional':True,'factsLanguagePairs':{'ru':ru,'zh':zh}}
        for direction,language,phrase,answer in [('ru-zh','Simplified Chinese',ru,zh),('zh-ru','Russian',zh,ru)]:
            rows.append({**common,'id':group+':'+direction,'task':'translation-'+direction,
                'messages':[{'role':'system','content':TRANSLATE_SYSTEM.format(language=language)},
                    {'role':'user','content':json.dumps({'text':phrase,'approvedGlossary':[]},ensure_ascii=False)},
                    {'role':'assistant','content':answer}]})
        request={'verifiedText':zh,'style':STYLES[(index-1)%len(STYLES)],
            'previousTextToAvoid':'','approvedStyleExamples':[],'variation':f'seed-v2-{index}'}
        rows.append({**common,'id':group+':json','task':'listing',
            'messages':[{'role':'system','content':LISTING_SYSTEM},
                {'role':'user','content':json.dumps(request,ensure_ascii=False)},
                {'role':'assistant','content':json.dumps({'title':title,'body':body},ensure_ascii=False)}]})
    splits={'train':[],'validation':[]}
    validation_groups=set(sorted({row['groupId'] for row in rows},
        key=lambda value:hashlib.sha256(value.encode()).hexdigest())[:8])
    for row in rows:
        role='validation' if row['groupId'] in validation_groups else 'train'
        splits[role].append(row)
    return validate_dataset({'version':1,'purpose':'balanced bilingual/JSON experiment v2; unaccepted',
        'provenance':{'source':'project-authored bilingual examples; not real listings',
            'scriptSha256':file_sha(__file__), 'evaluationExclusions':['74000/39 smoke probes not used'],
            'changes':'Contextual translation, preserved figures/negations/unknowns, matching runtime prompts and JSON schema.'},
        'splits':splits})


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--output',required=True)
    args=parser.parse_args(); target=Path(args.output)
    if target.exists(): raise ValueError('Preserve previous seeds; use a new output filename')
    value=prepare(); target.parent.mkdir(parents=True,exist_ok=True)
    target.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')
